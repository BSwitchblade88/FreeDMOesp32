class DmoLabelEmulator : public esphome::Component {
 public:
  // --- called by __init__.py's to_code() ---
  void set_slave_pins(int sda, int scl) { slave_sda_ = sda; slave_scl_ = scl; }
  void set_slave_address(uint8_t addr) { slave_address_ = addr; }
  void set_irq_pin(int pin) { irq_pin_ = pin; }

  // --- called by the YAML template select's on_value lambda ---
  void set_sku(uint8_t index);

  void setup() override;
  void loop() override {}  // all work happens on the dedicated I2C task, not here
  float get_setup_priority() const override { return esphome::setup_priority::HARDWARE; }
  void dump_config() override;

 protected:
  int slave_sda_{-1}, slave_scl_{-1};
  uint8_t slave_address_{0x28};
  int irq_pin_{-1};

  uint32_t blocks_[SLIX2_BLOCKS];  // working copy of the currently active SKU
  uint16_t counter_{0};
  bool tag_present_{false};
  SemaphoreHandle_t state_mutex_{nullptr};

  static void slave_task_trampoline(void *param);
  void slave_task();
  TaskHandle_t slave_task_handle_{nullptr};

  void handle_slix2_command(const uint8_t *in, uint8_t in_len, uint8_t *out, uint8_t *out_len);
  void handle_clrc688_command(const uint8_t *in, uint8_t in_len, uint8_t *out, uint8_t *out_len);
  void reset_counter();
};

