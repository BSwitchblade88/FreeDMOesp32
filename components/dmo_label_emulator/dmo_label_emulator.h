// =============================================================================
// dmo_label_emulator.h
//
// ESP32-S2 mini port of the FreeDMO STM32 firmware. This version:
//   - Emulates ONE virtual label tag at a time, switchable at runtime.
//   - Does NOT talk to a real RFID reader chip or sniff genuine tags -
//     it's a standalone, always-on emulation.
//   - Does NOT monitor printer power state or sleep - it just runs.
//   - Has NO custom select entity - the dropdown lives entirely in YAML
//     as a `template` select, which calls set_sku() through a lambda.
//   - Runs its I2C task pinned to core 0, since the S2 only has one core
//     (see dmo_label_emulator.cpp for why this matters).
//
// See dmo_label_emulator.cpp for the actual I2C driver + protocol logic.
// =============================================================================

